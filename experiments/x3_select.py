"""Select the active-set rule from saved X3 results (selection rule fixed 23 Nov 2026 before the X3 runs).

Score of a rule = certified share (tau = 0.05) of best-of(R0, R0s, Bs) at the largest basis size, averaged over all
available (benchmark, seed) files with equal weight per benchmark. Rules within TIE_PP percentage points of the best
score are tied; among tied rules the gap rule with the smallest tau_g is chosen, otherwise the best-scoring rule.

Outputs: results/x3/selection.json and paper/tables/x3_rules.tex (generated; no hand-typed numbers).
Usage:  python experiments/x3_select.py [--problems membrane block layered membrane_shift_mild] [--seeds 0 1 2]
"""

import argparse
import json
import logging
import sys

import numpy as np

from certcorrect.cli import EXIT_BAD_INPUT, EXIT_OK, setup_logging
from certcorrect.config import RESULTS, TABLES, result_path
from certcorrect.results_io import load_result

LOG = logging.getLogger("x3_select")
TIE_PP = 1.0
DEFAULT_PROBLEMS = ("membrane", "block", "layered", "membrane_shift_mild")


def gap_threshold(label: str) -> float | None:
    return float(label.split("_")[1]) if label.startswith("gap_") else None


def collect(problems, seeds) -> tuple[list[str], dict]:
    """Per benchmark, per rule: share, recall, over-snap, R0s / Bs relative error and effectivity (seed means)."""
    labels, table = None, {}
    for problem in problems:
        per_seed = []
        for s in seeds:
            path = result_path("x3", problem, s)
            if not path.is_file():
                LOG.warning("missing %s (skipped)", path)
                continue
            a, _ = load_result(path)
            labels = [str(x) for x in a["rule_labels"]] if labels is None else labels
            norm = a["norm_u"]
            per_seed.append({
                "share": np.nanmean(a["accepted_best"][:, -1], axis=1),
                "recall": np.nanmedian(a["recall"][:, -1], axis=1),
                "oversnap": np.nanmedian(a["oversnap"][:, -1], axis=1),
                "err_R0s": np.nanmedian(a["error_R0s"][:, -1] / norm, axis=1),
                "eff_R0s": np.nanmedian(a["delta_R0s"][:, -1] / a["error_R0s"][:, -1], axis=1),
                "err_Bs": np.nanmedian(a["error_Bs"][:, -1] / norm, axis=1),
                "eff_Bs": np.nanmedian(a["delta_Bs"][:, -1] / a["error_Bs"][:, -1], axis=1),
                "share_R0": np.nanmean(a["accepted_R0"][-1]),
            })
        if per_seed:
            table[problem] = {k: np.mean([d[k] for d in per_seed], axis=0) for k in per_seed[0]}
            table[problem]["n_seeds"] = len(per_seed)
    return labels, table


def select(labels: list[str], table: dict) -> tuple[str, np.ndarray]:
    score = 100 * np.mean([table[p]["share"] for p in table], axis=0)
    tied = [i for i in range(len(labels)) if score[i] >= score.max() - TIE_PP]
    gaps = [i for i in tied if gap_threshold(labels[i]) is not None]
    choice = min(gaps, key=lambda i: gap_threshold(labels[i])) if gaps else int(np.argmax(score))
    return labels[choice], score


def write_table(labels, table, score) -> None:
    problems = list(table)
    rows = [r"\begin{tabular}{l" + "r" * (3 * len(problems) + 1) + "}", r"\hline",
            "rule & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{p.replace('_', ' ')}}}" for p in problems)
            + r" & mean \\",
            " & " + " & ".join(["recall & over-snap & cert." for _ in problems]) + r" & cert. \\", r"\hline"]
    for i, label in enumerate(labels):
        cells = [f"{table[p]['recall'][i]:.2f} & {table[p]['oversnap'][i]:.2f} & {100 * table[p]['share'][i]:.0f}\\,\\%"
                 for p in problems]
        rows.append(label.replace("_", r"\_") + " & " + " & ".join(cells) + f" & {score[i]:.0f}\\,\\% \\\\")
    rows += [r"\hline", r"\end{tabular}"]
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "x3_rules.tex").write_text("% generated by experiments/x3_select.py\n" + "\n".join(rows) + "\n",
                                         encoding="utf-8")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--problems", nargs="+", default=list(DEFAULT_PROBLEMS))
    p.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    args = p.parse_args()
    setup_logging()
    labels, table = collect(args.problems, args.seeds)
    if not table:
        LOG.error("no X3 results found")
        return EXIT_BAD_INPUT
    choice, score = select(labels, table)
    for i, label in enumerate(labels):
        LOG.info("%-14s mean certified share %5.1f %% | %s", label, score[i], " | ".join(
            f"{pb}: {100 * table[pb]['share'][i]:.0f} % (rec {table[pb]['recall'][i]:.2f}, over {table[pb]['oversnap'][i]:.2f}, "
            f"R0s {100 * table[pb]['err_R0s'][i]:.1f} %/{table[pb]['eff_R0s'][i]:.2f}, "
            f"Bs {100 * table[pb]['err_Bs'][i]:.1f} %/{table[pb]['eff_Bs'][i]:.2f})" for pb in table))
    LOG.info("R0 alone: %s", ", ".join(f"{pb} {100 * table[pb]['share_R0']:.0f} %" for pb in table))
    LOG.info("SELECTED: %s (seeds per benchmark: %s)", choice, {pb: table[pb]["n_seeds"] for pb in table})
    out = RESULTS / "x3" / "selection.json"
    out.write_text(json.dumps({"selected": choice, "tie_pp": TIE_PP, "labels": labels, "score": score.tolist(),
                               "benchmarks": {pb: {k: (v.tolist() if hasattr(v, "tolist") else v)
                                                   for k, v in table[pb].items()} for pb in table}}, indent=2),
                   encoding="utf-8")
    write_table(labels, table, score)
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
